    /// `md(s)` from report.js: `String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim()`.
    private static func md(_ s: String) -> String {
        var out = ""
        var lastWasBreak = false
        for u in s.unicodeScalars {
            if u == "\n" {
                if !lastWasBreak { out.unicodeScalars.append(" ") }
                lastWasBreak = true
                continue
            }
            lastWasBreak = false
            if u == "|" { out.unicodeScalars.append("\\") }
            out.unicodeScalars.append(u)
        }
        return jsTrim(out)
    }

    private static func or(_ a: String, _ b: String) -> String { a.isEmpty ? b : a }

    /// Text equal to the code unit, which Swift's `==` (canonical equivalence) is not.
    private static func sameBytes(_ a: String, _ b: String) -> Bool { a.utf8.elementsEqual(b.utf8) }

    private static func lines(_ s: String) -> [String] { s.components(separatedBy: "\n") }

    /// The page's body, one converter output per line.
    private static func bodyLines(_ html: String) throws -> [String] {
        let start = try #require(html.range(of: "</style></head><body>"))
        #expect(html.hasSuffix("</body></html>"))
        return lines(String(html[start.upperBound...].dropLast("</body></html>".count)))
    }

