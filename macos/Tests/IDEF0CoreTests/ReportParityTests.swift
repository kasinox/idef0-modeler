    @Test("every golden issue of a scenario is a row of its Rule check table", arguments: ScenarioReplayer.names)
    func ruleCheckRows(_ name: String) throws {
        let golden = try #require(Self.scenarios[name]?.objectValue)
        let nodes = Dictionary(
            (golden["diagrams"]?.arrayValue ?? []).compactMap { d -> (String, String)? in
                guard let o = d.objectValue, let id = o["id"]?.stringValue, let node = o["node"]?.stringValue else { return nil }
                return (id, node)
            },
            uniquingKeysWith: { first, _ in first })
        let report = Report.markdown(try ScenarioReplayer.model(for: name), generatedOn: "DATE")
        let all = Self.lines(report)
        let start = try #require(all.lastIndex(of: "## Rule check"), "\(name): no Rule check section")
        let table = Array(all[start...])

        let issues = try #require(golden["issues"]?.arrayValue)
        for row in issues {
            let r = try #require(row.arrayValue)
            let severity = r[0].stringValue!, code = r[1].stringValue!, message = r[2].stringValue!
            #expect(table.contains { $0.contains(Self.md(message)) }, "\(name): no row carries “\(message)”")
            let node = Self.or(r[3].stringValue.flatMap { nodes[$0] } ?? "", "—")
            let line = "| \(severity) | \(node) | `\(code)` | \(Self.md(message)) |"
            #expect(table.contains { Self.sameBytes($0, line) }, "\(name): missing row \(line)")
        }
    }

