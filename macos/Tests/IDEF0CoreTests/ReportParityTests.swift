    /// toMarkdown's layout filled from a scenario's golden record alone: the
    /// saved file for the text, the tree for the order, and the web app's own
    /// sortedBoxes, ICOM codes, roles, concept queries and issues.
    private static func expectedReport(_ g: JSONObject) throws -> String {
        let roleLabel = ["input": "Input", "control": "Control", "output": "Output",
                         "mechanism": "Mechanism", "call": "Call", "unknown": "Unclassified"]
        let fileText = try #require(g["file"]?.stringValue)
        let file = try #require(try JSONValue.parse(fileText).objectValue)
        let fileDiagrams = try #require(file["diagrams"]?.objectValue)
        var goldenDiagrams: [String: JSONObject] = [:]
        for d in g["diagrams"]?.arrayValue ?? [] {
            if let o = d.objectValue, let id = o["id"]?.stringValue { goldenDiagrams[id] = o }
        }
        func str(_ v: JSONValue?) -> String { v?.stringValue ?? "" }
        func int(_ v: JSONValue?) -> Int {
            if case .number(let n)? = v { return Int(n) }
            return 0
        }
        func objects(_ v: JSONValue?) -> [JSONObject] { (v?.arrayValue ?? []).compactMap(\.objectValue) }
        /// Box positions in the order a golden's `sortedBoxes` names them. Ids
        /// can repeat in a model that duplicates one, so each is taken once.
        func sortedOrder(_ gd: JSONObject) -> [Int] {
            let boxes = objects(gd["boxes"])
            var taken = Set<Int>()
            var out: [Int] = []
            for id in (gd["sortedBoxes"]?.arrayValue ?? []).compactMap(\.stringValue) {
                guard let k = boxes.indices.first(where: { !taken.contains($0) && str(boxes[$0]["id"]) == id }) else { continue }
                taken.insert(k)
                out.append(k)
            }
            return out
        }

        let title = str(file["title"])
        var L: [String] = []
        L += ["# \(or(title, "Untitled IDEF0 Model"))", ""]
        L += ["| | |", "|---|---|"]
        for (label, key) in [("Author", "author"), ("Project", "project"), ("Status", "status"), ("Created", "created"), ("Revised", "revised")] {
            L.append("| \(label) | \(md(str(file[key]))) |")
        }
        L.append("")
        L += ["**Purpose.** " + or(jsTrim(str(file["purpose"])), "_not stated_"), ""]
        L += ["**Viewpoint.** " + or(jsTrim(str(file["viewpoint"])), "_not stated_"), ""]

        let tree = (g["tree"]?.arrayValue ?? []).compactMap { $0.arrayValue?.first?.stringValue }
        L += ["## Node index", ""]
        // Every box is listed; a detail diagram already on the path (a
        // decomposition cycle) is not entered again.
        var path = Set<String>()
        func walk(_ id: String, _ depth: Int) {
            guard let gd = goldenDiagrams[id] else { return }
            path.insert(id)
            defer { path.remove(id) }
            let boxes = objects(gd["boxes"])
            for b in sortedOrder(gd).map({ boxes[$0] }) {
                L.append("\(String(repeating: "  ", count: depth))- **\(str(b["node"]))** \(or(str(b["name"]), "_(unnamed)_"))")
                let child = str(b["childDiagramId"])
                if !child.isEmpty, goldenDiagrams[child] != nil, !path.contains(child) { walk(child, depth + 1) }
            }
        }
        if let root = tree.first { walk(root, 0) }
        L.append("")

        L += ["## Diagrams", ""]
        for id in tree {
            let gd = try #require(goldenDiagrams[id]), fd = try #require(fileDiagrams[id]?.objectValue)
            L += ["### \(str(gd["node"])) — \(or(str(gd["title"]), title))", ""]
            if !str(fd["cNumber"]).isEmpty { L += ["C-number: `\(str(fd["cNumber"]))`", ""] }

            let goldenBoxes = objects(gd["boxes"]), fileBoxes = objects(fd["boxes"])
            let sorted = sortedOrder(gd)
            L += ["**Activities**", ""]
            L += ["| Box | Node | Name | Decomposed |", "|---|---|---|---|"]
            for b in sorted.map({ goldenBoxes[$0] }) {
                // "yes" only when the link names a diagram the model holds.
                let decomposed = goldenDiagrams[str(b["childDiagramId"])] == nil ? "no" : "yes"
                L.append("| \(int(b["number"])) | \(str(b["node"])) | \(or(md(str(b["name"])), "_(unnamed)_")) | \(decomposed) |")
            }
            L.append("")

            var codes: [String: String] = [:]
            for row in gd["icom"]?.arrayValue ?? [] {
                guard let r = row.arrayValue, let code = r[2].stringValue else { continue }
                codes["\(str(r[0])):\(str(r[1]))"] = code
            }
            func endDesc(_ e: JSONObject) -> String {
                if str(e["type"]) == "boundary" { return "boundary \(str(e["side"]))" }
                guard let b = fileBoxes.first(where: { str($0["id"]) == str(e["boxId"]) }) else { return "missing box" }
                return "box \(int(b["number"])) \(str(e["side"]))"
            }
            L += ["**Arrows**", ""]
            L += ["| Role | Label | From | To | ICOM | Tunnel |", "|---|---|---|---|---|---|"]
            let goldenArrows = objects(gd["arrows"])
            for (k, a) in objects(fd["arrows"]).enumerated() {
                let role = try #require(roleLabel[str(goldenArrows[k]["role"])])
                let code = or(codes["\(str(a["id"])):from"] ?? "", codes["\(str(a["id"])):to"] ?? "")
                let tunnel = a["tunnelFrom"] == .bool(true) || a["tunnelTo"] == .bool(true) ? "yes" : ""
                let from = endDesc(try #require(a["from"]?.objectValue)), to = endDesc(try #require(a["to"]?.objectValue))
                L.append("| \(role) | \(or(md(str(a["label"])), "_(unlabelled)_")) | \(from) | \(to) | \(code) | \(tunnel) |")
            }
            L.append("")

            let notes = sorted.filter { !jsTrim(str(fileBoxes[$0]["note"])).isEmpty }
            if !notes.isEmpty {
                L += ["**Notes**", ""]
                for k in notes {
                    let node = str(goldenBoxes[k]["node"])
                    L.append("- **\(node)** — \(md(str(fileBoxes[k]["note"])))")
                }
                L.append("")
            }
        }

        let concepts = try #require(g["concepts"]?.objectValue)
        let glossary = (concepts["glossary"]?.arrayValue ?? []).compactMap(\.arrayValue)
        if !glossary.isEmpty {
            let usage = (concepts["usage"]?.arrayValue ?? []).compactMap(\.arrayValue)
            let occurrences = (concepts["occurrences"]?.arrayValue ?? []).compactMap(\.arrayValue)
            L += ["## Concepts", ""]
            L += ["| Term | Kind | Used | Occurs on | Definition |", "|---|---|---|---|---|"]
            for (k, c) in glossary.enumerated() {
                let whereUsed = objects(occurrences[k][1])
                    .map { "\(str($0["node"]))\u{00A0}\(str($0["kind"]) == "box" ? "act" : "obj")" }
                    .joined(separator: ", ")
                L.append("| \(md(str(c[1]))) | \(str(c[2])) | \(int(usage[k][1])) | \(or(whereUsed, "—")) | \(or(md(str(c[3])), "_undefined_")) |")
            }
            L.append("")

            let drift = objects(concepts["drift"])
            if !drift.isEmpty {
                L += ["### Label elaboration", ""]
                L += ["Places where the drawn text differs from the concept it denotes — legitimate under FIPS 183 §3.3.2.4.", ""]
                L += ["| Where | Reads | Concept |", "|---|---|---|"]
                for d in drift {
                    L.append("| \(str(d["node"])) \(str(d["kind"]) == "box" ? "activity" : "arrow") | \(md(str(d["text"]))) | \(md(str(d["term"]))) |")
                }
                L.append("")
            }

            let unused = (concepts["unused"]?.arrayValue ?? []).compactMap(\.stringValue)
            if !unused.isEmpty {
                let terms = unused.map { id in md(str(glossary.first { str($0[0]) == id }?[1])) }
                L += ["_\(unused.count) concept(s) defined but not used: \(terms.joined(separator: ", "))._", ""]
            }
        }

        let summary = try #require(g["summary"]?.objectValue)
        let issues = (g["issues"]?.arrayValue ?? []).compactMap(\.arrayValue)
        L += ["## Rule check", ""]
        L += ["\(int(summary["errors"])) error(s), \(int(summary["warnings"])) warning(s).", ""]
        if !issues.isEmpty {
            L += ["| Severity | Diagram | Rule | Detail |", "|---|---|---|---|"]
            for i in issues {
                let node = or(i[3].stringValue.flatMap { goldenDiagrams[$0].map { str($0["node"]) } } ?? "", "—")
                L.append("| \(str(i[0])) | \(node) | `\(str(i[1]))` | \(md(str(i[2]))) |")
            }
            L.append("")
        }
        L += ["---", "", "_Generated by IDEF0 Modeler on DATE._"]
        return L.joined(separator: "\n")
    }

